CREATE TABLE `activity_records` (
  `record_id` BIGINT UNSIGNED NOT NULL PRIMARY KEY,
  `kind` VARCHAR(16) NOT NULL DEFAULT 'activity',
  `activity_type_id` BIGINT UNSIGNED NULL,
  `activity_reference_id` BIGINT UNSIGNED NULL,
  `duration_minutes` DECIMAL(12,4) NULL,
  CHECK (`duration_minutes` >= 0),
  `energy_origin` VARCHAR(16) NOT NULL,
  `reported_kcal` DECIMAL(12,4) NOT NULL,
  CHECK (`reported_kcal` >= 0),
  `reported_energy_kind` VARCHAR(16) NOT NULL,
  `resting_kcal_deducted` DECIMAL(12,4) NOT NULL DEFAULT 0,
  CHECK (`resting_kcal_deducted` >= 0),
  `active_kcal` DECIMAL(12,4) NOT NULL,
  CHECK (`active_kcal` >= 0),
  `weight_used_kg` DECIMAL(12,4) NULL,
  CHECK (`weight_used_kg` >= 0),
  `met_used` DECIMAL(6,3) NULL,
  CHECK (`met_used` >= 0),
  `calculation_method` VARCHAR(64) NULL,
  `calculation_version` VARCHAR(32) NULL,
  `provider_source_id` BIGINT UNSIGNED NULL,
  `provider_record_id` VARCHAR(191) COLLATE utf8mb4_0900_bin NULL,
  `provenance_snapshot` JSON NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  FOREIGN KEY (`record_id`,`kind`) REFERENCES `records` (`id`,`kind`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CHECK (kind='activity'),
  FOREIGN KEY (`activity_reference_id`,`activity_type_id`) REFERENCES `activity_references` (`id`,`activity_type_id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CHECK (activity_reference_id IS NULL OR activity_type_id IS NOT NULL),
  CHECK (duration_minutes > 0),
  CHECK (weight_used_kg > 0),
  CHECK (met_used > 0),
  CHECK (`energy_origin` IN ('manual','device','met')),
  CHECK (`reported_energy_kind` IN ('active','total')),
  CHECK (resting_kcal_deducted <= reported_kcal),
  CHECK (active_kcal=reported_kcal-resting_kcal_deducted),
  CHECK (reported_energy_kind<>'active' OR resting_kcal_deducted=0),
  CHECK (energy_origin<>'met' OR (activity_reference_id IS NOT NULL AND activity_type_id IS NOT NULL AND weight_used_kg IS NOT NULL AND met_used IS NOT NULL AND duration_minutes IS NOT NULL AND calculation_method IS NOT NULL AND calculation_version IS NOT NULL AND provenance_snapshot IS NOT NULL)),
  CHECK (provider_record_id IS NULL OR provider_source_id IS NOT NULL),
  INDEX (`provider_source_id`,`provider_record_id`),
  FOREIGN KEY (`activity_type_id`) REFERENCES `activity_types` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  FOREIGN KEY (`provider_source_id`) REFERENCES `data_sources` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
