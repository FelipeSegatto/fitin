CREATE TABLE `ai_requests` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `user_id` BIGINT UNSIGNED NOT NULL,
  `job_id` BIGINT UNSIGNED NULL,
  `client_request_id` VARCHAR(64) COLLATE utf8mb4_0900_bin NOT NULL,
  `use_case` VARCHAR(32) NOT NULL,
  `provider` VARCHAR(64) NOT NULL,
  `model` VARCHAR(120) NOT NULL,
  `prompt_version` VARCHAR(64) NOT NULL,
  `output_schema_version` VARCHAR(32) NOT NULL,
  `input_text` TEXT NULL,
  `input_object_key` VARCHAR(500) NULL,
  `input_sha256` BINARY(32) NOT NULL,
  `input_deleted_at` DATETIME(6) NULL,
  `status` VARCHAR(16) NOT NULL,
  `input_tokens` INT UNSIGNED NULL,
  `output_tokens` INT UNSIGNED NULL,
  `cached_input_tokens` INT UNSIGNED NULL,
  `cost_amount` DECIMAL(14,8) NULL,
  CHECK (`cost_amount` >= 0),
  `cost_currency` CHAR(3) NULL,
  `pricing_version` VARCHAR(64) NULL,
  `completed_at` DATETIME(6) NULL,
  `expires_at` DATETIME(6) NOT NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  UNIQUE (`user_id`,`client_request_id`),
  UNIQUE (`id`,`user_id`),
  CHECK ((input_deleted_at IS NULL AND ((input_text IS NOT NULL) <> (input_object_key IS NOT NULL))) OR (input_deleted_at IS NOT NULL AND input_text IS NULL AND input_object_key IS NULL)),
  CHECK (`use_case` IN ('food_parse','label_ocr','query_translation')),
  CHECK (`status` IN ('pending','running','succeeded','failed','cancelled')),
  CHECK ((cost_amount IS NULL) = (cost_currency IS NULL)),
  CHECK (expires_at > created_at),
  CHECK (cached_input_tokens IS NULL OR (input_tokens IS NOT NULL AND cached_input_tokens <= input_tokens)),
  CHECK ((status IN ('pending','running') AND completed_at IS NULL) OR (status IN ('succeeded','failed','cancelled') AND completed_at IS NOT NULL)),
  INDEX (`user_id`,`created_at`,`id`),
  INDEX (`status`,`created_at`,`id`),
  FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  FOREIGN KEY (`job_id`) REFERENCES `processing_jobs` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
