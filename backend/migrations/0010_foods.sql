CREATE TABLE `foods` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `owner_user_id` BIGINT UNSIGNED NULL,
  `visibility` VARCHAR(16) NOT NULL,
  `kind` VARCHAR(24) NOT NULL,
  `name` VARCHAR(160) NOT NULL,
  `brand` VARCHAR(120) NULL,
  `barcode` VARCHAR(14) NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'active',
  `merged_into_food_id` BIGINT UNSIGNED NULL,
  `row_version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CHECK (`row_version` > 0),
  `product_line` VARCHAR(100) NULL,
  `flavor` VARCHAR(100) NULL,
  `presentation` VARCHAR(160) NULL,
  CHECK (`visibility` IN ('private','public')),
  CHECK (`kind` IN ('generic_food','packaged_product')),
  CHECK (`status` IN ('active','archived','merged')),
  CHECK ((visibility='private' AND owner_user_id IS NOT NULL) OR (visibility='public' AND owner_user_id IS NULL)),
  CHECK ((status='merged' AND merged_into_food_id IS NOT NULL) OR (status<>'merged' AND merged_into_food_id IS NULL)),
  CHECK (barcode IS NULL OR REGEXP_LIKE(barcode, '^([0-9]{8}|[0-9]{12}|[0-9]{13}|[0-9]{14})$', 'c')),
  INDEX (`owner_user_id`,`status`,`id`),
  INDEX (`visibility`,`status`,`id`),
  INDEX (`barcode`),
  FULLTEXT INDEX (`name`,`brand`),
  FOREIGN KEY (`owner_user_id`) REFERENCES `users` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  FOREIGN KEY (`merged_into_food_id`) REFERENCES `foods` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
