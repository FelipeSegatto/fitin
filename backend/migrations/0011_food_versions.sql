CREATE TABLE `food_versions` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `food_id` BIGINT UNSIGNED NOT NULL,
  `version_no` INT UNSIGNED NOT NULL,
  `label_amount` DECIMAL(12,4) NOT NULL,
  CHECK (`label_amount` >= 0),
  `label_unit` VARCHAR(4) NOT NULL,
  `label_kcal` DECIMAL(12,4) NOT NULL,
  CHECK (`label_kcal` >= 0),
  `label_protein_g` DECIMAL(12,4) NULL,
  CHECK (`label_protein_g` >= 0),
  `label_carbs_g` DECIMAL(12,4) NULL,
  CHECK (`label_carbs_g` >= 0),
  `label_fat_g` DECIMAL(12,4) NULL,
  CHECK (`label_fat_g` >= 0),
  `density_g_per_ml` DECIMAL(12,4) NULL,
  CHECK (`density_g_per_ml` >= 0),
  `source_snapshot_id` BIGINT UNSIGNED NULL,
  `source_id` BIGINT UNSIGNED NOT NULL,
  `created_by_user_id` BIGINT UNSIGNED NULL,
  `verification_status` VARCHAR(24) NOT NULL,
  `normalization_version` VARCHAR(32) NOT NULL,
  `validation_version` VARCHAR(32) NOT NULL,
  `validated_at` DATETIME(6) NOT NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `kcal_per100` DECIMAL(16,6) GENERATED ALWAYS AS (ROUND(label_kcal * 100 / NULLIF(label_amount,0),6)) STORED,
  `protein_per100_g` DECIMAL(16,6) GENERATED ALWAYS AS (ROUND(label_protein_g * 100 / NULLIF(label_amount,0),6)) STORED,
  `carbs_per100_g` DECIMAL(16,6) GENERATED ALWAYS AS (ROUND(label_carbs_g * 100 / NULLIF(label_amount,0),6)) STORED,
  `fat_per100_g` DECIMAL(16,6) GENERATED ALWAYS AS (ROUND(label_fat_g * 100 / NULLIF(label_amount,0),6)) STORED,
  UNIQUE (`food_id`,`version_no`),
  UNIQUE (`id`,`food_id`),
  CHECK (version_no > 0),
  CHECK (label_amount > 0),
  CHECK (`label_unit` IN ('g','ml')),
  CHECK (density_g_per_ml > 0),
  CHECK (`verification_status` IN ('unverified','source_imported','curated')),
  FOREIGN KEY (`food_id`) REFERENCES `foods` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  FOREIGN KEY (`source_snapshot_id`) REFERENCES `source_snapshots` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  FOREIGN KEY (`source_id`) REFERENCES `data_sources` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  FOREIGN KEY (`created_by_user_id`) REFERENCES `users` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
