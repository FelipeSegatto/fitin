CREATE TABLE `body_measurements` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `user_id` BIGINT UNSIGNED NOT NULL,
  `measured_at` DATETIME(6) NOT NULL,
  `local_date` DATE NOT NULL,
  `timezone` VARCHAR(64) NOT NULL,
  `weight_kg` DECIMAL(12,4) NULL,
  CHECK (`weight_kg` >= 0),
  `height_cm` DECIMAL(12,4) NULL,
  CHECK (`height_cm` >= 0),
  `neck_cm` DECIMAL(12,4) NULL,
  CHECK (`neck_cm` >= 0),
  `waist_cm` DECIMAL(12,4) NULL,
  CHECK (`waist_cm` >= 0),
  `hip_cm` DECIMAL(12,4) NULL,
  CHECK (`hip_cm` >= 0),
  `origin` VARCHAR(16) NOT NULL DEFAULT 'manual',
  `note` VARCHAR(500) NULL,
  `row_version` INT UNSIGNED NOT NULL DEFAULT 1,
  `deleted_at` DATETIME(6) NULL,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CHECK (`row_version` > 0),
  UNIQUE (`id`,`user_id`),
  CHECK (weight_kg IS NOT NULL OR height_cm IS NOT NULL OR neck_cm IS NOT NULL OR waist_cm IS NOT NULL OR hip_cm IS NOT NULL),
  CHECK (weight_kg > 0),
  CHECK (height_cm > 0),
  CHECK (neck_cm > 0),
  CHECK (waist_cm > 0),
  CHECK (hip_cm > 0),
  CHECK (`origin` IN ('manual','device','import')),
  INDEX (`user_id`,`local_date`,`measured_at`,`id`),
  FOREIGN KEY (`user_id`) REFERENCES `users` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
