CREATE TABLE `meal_items` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
  `meal_record_id` BIGINT UNSIGNED NOT NULL,
  `food_version_id` BIGINT UNSIGNED NULL,
  `position` SMALLINT UNSIGNED NOT NULL,
  `name_snapshot` VARCHAR(200) NOT NULL,
  `quantity` DECIMAL(12,4) NULL,
  CHECK (`quantity` >= 0),
  `unit` VARCHAR(4) NULL,
  `kcal` DECIMAL(12,4) NOT NULL,
  CHECK (`kcal` >= 0),
  `protein_g` DECIMAL(12,4) NULL,
  CHECK (`protein_g` >= 0),
  `carbs_g` DECIMAL(12,4) NULL,
  CHECK (`carbs_g` >= 0),
  `fat_g` DECIMAL(12,4) NULL,
  CHECK (`fat_g` >= 0),
  `calculation_method` VARCHAR(32) NOT NULL,
  `calculation_version` VARCHAR(32) NOT NULL,
  `provenance_snapshot` JSON NULL,
  `row_version` INT UNSIGNED NOT NULL DEFAULT 1,
  `created_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  `updated_at` DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  CHECK (`row_version` > 0),
  UNIQUE (`meal_record_id`,`position`),
  CHECK ((quantity IS NULL) = (unit IS NULL)),
  CHECK (quantity > 0),
  CHECK (`unit` IN ('g','ml')),
  CHECK (`calculation_method` IN ('manual_totals','catalog_portion')),
  CHECK ((calculation_method='manual_totals' AND food_version_id IS NULL) OR (calculation_method='catalog_portion' AND food_version_id IS NOT NULL AND quantity IS NOT NULL AND unit IS NOT NULL AND provenance_snapshot IS NOT NULL)),
  FOREIGN KEY (`meal_record_id`) REFERENCES `meal_records` (`record_id`) ON UPDATE RESTRICT ON DELETE RESTRICT,
  FOREIGN KEY (`food_version_id`) REFERENCES `food_versions` (`id`) ON UPDATE RESTRICT ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
