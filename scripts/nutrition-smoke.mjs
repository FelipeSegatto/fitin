import { chromium } from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try {
  await page.goto(process.env.BASE_URL||'http://localhost:5200');
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await page.getByRole('button',{name:'Preencher dados',exact:true}).click();
  await page.getByRole('button',{name:'Entrar',exact:true}).click();
  await page.getByRole('button',{name:'Adicionar alimentos',exact:true}).click();
  await page.getByRole('button',{name:'Buscar na base nutricional'}).click();
  await page.getByLabel('Buscar alimento ou código de barras').fill('150 g de arroz cozido');
  await page.getByRole('button',{name:'Pesquisar alimentos',exact:true}).click();
  await page.getByRole('button',{name:/Arroz, tipo 1, cozido/}).click();
  assert.equal(await page.getByLabel('Quantidade (g)',{exact:true}).inputValue(),'150');
  assert.ok((await page.locator('.food-portion-values').innerText()).includes('192 kcal'));
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'/tmp/fitin-nutrition-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Usar alimento',exact:true}).click();
  assert.equal(await page.getByLabel('Energia (kcal)').inputValue(),'192');
  assert.equal(await page.getByLabel('Proteínas (g)').inputValue(),'3.8');
  await page.getByRole('button',{name:'Adicionar registro',exact:true}).click();
  await page.getByRole('button',{name:'Diário',exact:true}).click();
  await page.locator('.entry-nutrition-source').getByRole('link').waitFor();
  await page.getByRole('button',{name:'Editar Arroz, tipo 1, cozido (150 g)',exact:true}).click();
  await page.getByLabel('Energia (kcal)').fill('200');
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
  assert.equal(await page.locator('.entry-nutrition-source').count(),0);
  await page.getByRole('button',{name:'Home',exact:true}).click();
  await page.getByRole('button',{name:'Adicionar alimentos',exact:true}).click();
  await page.getByRole('button',{name:'Buscar na base nutricional'}).click();
  // Fixture verifies external UI handling; this is not a live API check.
  await page.route('**/api/nutrition/search?**',route=>route.fulfill({status:200,json:{version:1,source:'off',retrievedAt:new Date().toISOString(),foods:[{id:'off:12345678',source:'off',sourceName:'Open Food Facts',sourceId:'12345678',sourceUrl:'https://world.openfoodfacts.org/product/12345678',sourceVersion:'test fixture',name:'Bebida de teste',basis:{amount:100,unit:'ml'},per100:{kcal:0,protein:0,carbs:0,fat:null},qualifiers:{}}]}}));
  await page.getByLabel('Fonte nutricional').selectOption('off');
  await page.getByLabel('Buscar alimento ou código de barras').fill('250 ml de bebida');
  await page.getByRole('button',{name:'Pesquisar alimentos',exact:true}).click();
  await page.getByRole('button',{name:/Bebida de teste/}).click();
  assert.equal(await page.getByLabel('Quantidade (ml)',{exact:true}).inputValue(),'250');
  await page.setViewportSize({width:1440,height:1000});
  await page.screenshot({path:'/tmp/fitin-nutrition-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Usar alimento',exact:true}).click();
  assert.equal(await page.getByLabel('Energia (kcal)').inputValue(),'0');
  assert.equal(await page.getByLabel('Proteínas (g)').inputValue(),'0');
  assert.equal(await page.getByLabel('Gorduras (g)').inputValue(),'');
  await page.getByRole('button',{name:'Adicionar registro',exact:true}).click();
  await page.getByRole('button',{name:'Diário',exact:true}).click();
  await page.getByText('Bebida de teste (250 ml)',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Home',exact:true}).click();
  await page.getByRole('button',{name:'Adicionar alimentos',exact:true}).click();
  await page.getByRole('button',{name:'Buscar na base nutricional'}).click();
  await page.unroute('**/api/nutrition/search?**');
  await page.route('**/api/nutrition/search?**',route=>route.fulfill({status:429,json:{error:'rate_limited',message:'O limite de consultas desta fonte foi atingido.'}}));
  await page.getByLabel('Fonte nutricional').selectOption('usda');
  await page.getByLabel('Buscar alimento ou código de barras').fill('rice');
  await page.getByRole('button',{name:'Pesquisar alimentos',exact:true}).click();
  await page.getByRole('status').getByText('O limite de consultas desta fonte foi atingido.',{exact:true}).waitFor();
  await page.getByLabel('Alimento ou refeição').fill('Registro manual após erro');
  await page.getByLabel('Energia (kcal)').fill('100');
  await page.getByRole('button',{name:'Adicionar registro',exact:true}).click();
  await page.getByRole('button',{name:'Diário',exact:true}).click();
  await page.getByText('Registro manual após erro',{exact:true}).waitFor();
  assert.deepEqual(errors,[]);
  console.log('PASS: real local TACO search, portions/macros/provenance, manual correction, liquid/zero/missing nutrient fixture, mobile and desktop.');
} finally {await browser.close();}
