import {chromium} from 'playwright';
import assert from 'node:assert/strict';
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH||'/usr/bin/chromium',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:390,height:844}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
try{
 await page.goto(process.env.BASE_URL||'http://localhost:5200');
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.getByRole('button',{name:'Preencher dados',exact:true}).click();
 await page.getByRole('button',{name:'Entrar',exact:true}).click();
 await page.getByRole('button',{name:'Adicionar atividades',exact:true}).click();
 await page.getByRole('button',{name:'Estimar calorias da atividade'}).click();
 assert.equal(await page.getByLabel('Peso usado na estimativa (kg)',{exact:true}).inputValue(),'78');
 await page.getByLabel('Peso usado na estimativa (kg)',{exact:true}).fill('');
 assert.equal(await page.getByRole('button',{name:'Usar estimativa',exact:true}).isDisabled(),true);
 await page.getByLabel('Peso usado na estimativa (kg)',{exact:true}).fill('78');
 await page.getByLabel('Modalidade e ritmo').selectOption('cycling-leisure');
 await page.getByLabel('Tempo da atividade (min)',{exact:true}).fill('30');
 assert.ok((await page.locator('.activity-estimate').innerText()).includes('123 kcal ativas'));
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await page.screenshot({path:'/tmp/fitin-activity-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Usar estimativa',exact:true}).click();
 assert.equal(await page.getByLabel('Energia (kcal)').inputValue(),'123');
 assert.equal(await page.getByLabel('Duração (min)',{exact:true}).inputValue(),'30');
 assert.equal(await page.getByLabel('Origem das calorias').inputValue(),'met');
 await page.getByRole('button',{name:'Adicionar registro',exact:true}).click();
 assert.equal(await page.locator('.ring strong').innerText(),'1.347');
 await page.getByRole('button',{name:'Diário',exact:true}).click();
 await page.locator('.entry-activity-source').getByRole('link').waitFor();
 await page.getByRole('button',{name:'Editar Bicicleta',exact:true}).click();
 await page.getByLabel('Horário',{exact:true}).fill('17:30');
 await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
 assert.equal(await page.locator('.entry-activity-source a').count(),1);
 await page.getByRole('button',{name:'Editar Bicicleta',exact:true}).click();
 await page.getByLabel('Duração (min)',{exact:true}).fill('40');
 assert.equal(await page.getByLabel('Origem das calorias').inputValue(),'manual');
 assert.equal(await page.locator('.activity-provenance').count(),0);
 await page.getByLabel('Origem das calorias').selectOption('device');
 await page.getByLabel('Energia (kcal)').fill('150');
 await page.setViewportSize({width:1440,height:1000});
 await page.screenshot({path:'/tmp/fitin-activity-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
 await page.getByText('Calorias ativas informadas · relógio ou aplicativo',{exact:true}).waitFor();
 assert.equal(await page.locator('.entry-activity-source a').count(),0);
 await page.getByRole('button',{name:'Home',exact:true}).click();
 assert.equal(await page.locator('.ring strong').innerText(),'1.374');
 assert.deepEqual(errors,[]);
 console.log('PASS: activity estimate, required weight, active energy, source, edit preservation/invalidation, device input, shared totals, mobile and desktop.');
}finally{await browser.close()}
